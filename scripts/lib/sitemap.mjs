// @ts-check
/* The one sitemap writer, shared by build-field-pages.mjs, build-course-pages.mjs and build-info-pages.mjs.
 * Each calls writeSitemap() last, so the sitemap is complete whichever one ran.
 *
 * <lastmod> is given only where the page shows a date of its own, and is that date:
 *   courses/<id>.html            the latest date any of its requirements was checked (lastVerified)
 *   universities/<slug>.html     the latest of those dates across its courses
 *   courses/, universities/      the latest across every course page
 *   privacy, terms, accessibility  the page's "Last updated" date
 * The landing page, the app and the field guides show no date, so they get no <lastmod>. */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { ROOT, loadConfig, loadCourses, loadCycle } from './requirements-io.mjs';
import { SITE, sitemapUrls } from './site-pages.mjs';
import { buildModel } from './course-pages.mjs';
import { INFO_PAGE_CONTENT, LAST_UPDATED } from './info-pages.mjs';

const require = createRequire(import.meta.url);
const ISO = /^\d{4}-\d{2}-\d{2}$/;

/** The latest lastVerified in one requirements record, or null. @param {Record<string, any> | undefined} record */
function latestCheck(record) {
  const dates = Object.values(record ?? {}).map(e => e?.lastVerified).filter(d => typeof d === 'string' && ISO.test(d));
  return dates.length ? dates.sort().at(-1) ?? null : null;
}
/** @param {Array<string | null>} dates */
const latest = dates => dates.filter(Boolean).sort().at(-1) ?? null;

/** URL → lastmod (YYYY-MM-DD) for every page that shows a date. */
export function sitemapLastmod() {
  const config = loadConfig();
  const { fieldProfiles } = require(path.join(ROOT, 'data/fieldProfiles.js'));
  const { universityProfiles } = require(path.join(ROOT, 'data/university-profiles.js'));
  const model = buildModel({ courses: loadCourses(), cycle: loadCycle(config.currentCycle), config, fieldProfiles, universityProfiles });
  /** @type {Map<string, string>} */
  const out = new Map();
  const set = (/** @type {string} */ url, /** @type {string | null} */ d) => { if (d) out.set(url, d); };
  const courseDate = (/** @type {any} */ c) => latestCheck(model.record(c));
  for (const c of model.paged) set(`${SITE}/courses/${c.id}.html`, courseDate(c));
  for (const u of model.pagedUniversities) set(`${SITE}/universities/${u.slug}.html`, latest(u.courses.map(courseDate)));
  const all = latest(model.paged.map(courseDate));
  set(`${SITE}/courses/`, all);
  set(`${SITE}/universities/`, all);
  for (const p of INFO_PAGE_CONTENT) set(`${SITE}/${p.file}`, (p.updated ?? LAST_UPDATED).iso);
  return out;
}

/**
 * Rewrite sitemap.xml from the generated pages on disk.
 * @param {string} [root]
 * @returns {number} how many URLs were written
 */
export function writeSitemap(root = ROOT) {
  const urls = sitemapUrls(root);
  const lastmod = sitemapLastmod();
  fs.writeFileSync(path.join(root, 'sitemap.xml'),
    `<?xml version="1.0" encoding="UTF-8"?>\n<!-- Generated by scripts/lib/sitemap.mjs (build-field-pages.mjs, build-course-pages.mjs, build-info-pages.mjs) — do not edit by hand. -->\n` +
    `<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n` +
    urls.map(u => `  <url>\n    <loc>${u}</loc>${lastmod.has(u) ? `\n    <lastmod>${lastmod.get(u)}</lastmod>` : ''}\n  </url>`).join('\n') + `\n</urlset>\n`);
  return urls.length;
}
