#!/usr/bin/env node
// @ts-check
/* ═══════════════════════════════════════════════════════════════
 * npm run report — writes docs/requirements-review.md: the central list
 * of every requirement that is NOT verified for the current cycle, every
 * partly-verified one (with what is unconfirmed), every value recorded
 * without a source, and reviewer hints mined from the existing verified
 * course notes (pointers only — nothing is transcribed automatically).
 *
 * Generated: re-run after any data change. `npm run validate` fails if
 * the committed report is out of date.
 * ═══════════════════════════════════════════════════════════════ */

import fs from 'node:fs';
import path from 'node:path';
import { ROOT, loadConfig, loadCourses, loadCycle } from './lib/requirements-io.mjs';

export const REPORT_PATH = path.join(ROOT, 'docs', 'requirements-review.md');

// Words in a course's existing (verified) source notes that suggest a
// requirement in a category that is still unverified. A hint is a pointer
// for a human reviewer — never a value.
const HINTS = [
  { category: 'englishLanguage',   re: /\b(IELTS|TOEFL|Duolingo|English language requirement|English requirement)\b/i, label: 'notes mention an English-language test' },
  { category: 'otherRequirements', re: /\b(interview(s|ed)?|portfolio|audition)\b/i, label: 'notes mention an interview / portfolio / audition' },
  { category: 'satAct',            re: /\b(SAT|ACT)\b/, label: 'notes mention SAT/ACT' },
];

/** Build the report markdown (pure, so validate can compare it). */
export function buildReport() {
  const config = loadConfig();
  const cycleId = config.currentCycle;
  const cycle = loadCycle(cycleId);
  const courses = loadCourses();
  const cats = config.categories;

  /** @type {Record<string, Record<string, number>>} */
  const tally = {};
  const unverified = [];
  const partial = [];
  const recorded = [];
  for (const c of courses) {
    const rec = cycle.courses[c.id] ?? {};
    const missing = [];
    for (const cat of cats) {
      const e = rec[cat.id];
      const st = e?.status ?? 'unverified';
      (tally[cat.id] ??= { verified: 0, partial: 0, unverified: 0 })[st]++;
      if (st === 'unverified') {
        missing.push(cat.label);
        if (e?.recorded) recorded.push({ c, cat, value: e.recorded });
      }
      if (st === 'partial') partial.push({ c, cat, note: e?.note ?? '' });
    }
    const notes = `${c.verification?.notes ?? ''} ${c.notes ?? ''}`;
    const hints = HINTS.filter(h => (rec[h.category]?.status ?? 'unverified') === 'unverified' && h.re.test(notes)).map(h => h.label);
    if (missing.length) unverified.push({ c, missing, hints });
  }

  const md = (/** @type {string} */ s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
  const L = [];
  L.push(`# Requirements review — ${config.cycles[cycleId].label}`);
  L.push('');
  L.push('> Generated by `npm run report` from `data/requirements/' + cycleId + '.js`. Do not edit by hand.');
  L.push('> Everything listed here is shown to students as **Not verified** or **Partly verified** until a');
  L.push('> reviewer checks it against the official source and updates the cycle file (see `docs/requirements-data.md`).');
  L.push('');
  L.push('## Coverage');
  L.push('');
  L.push('| Category | Verified | Partly verified | Not verified |');
  L.push('|---|---:|---:|---:|');
  for (const cat of cats) {
    const t = tally[cat.id] ?? { verified: 0, partial: 0, unverified: 0 };
    L.push(`| ${cat.label} | ${t.verified} | ${t.partial} | ${t.unverified} |`);
  }
  L.push('');
  L.push(`${courses.length} courses × ${cats.length} categories = ${courses.length * cats.length} requirement entries.`);
  L.push('');

  L.push('## Partly verified');
  L.push('');
  L.push('Shown with a "Partly verified" badge and the note below.');
  L.push('');
  L.push('| Course | Category | What is unconfirmed |');
  L.push('|---|---|---|');
  for (const p of partial) L.push(`| \`${p.c.id}\` | ${p.cat.label} | ${md(p.note)} |`);
  L.push('');

  L.push('## Previously recorded values awaiting verification');
  L.push('');
  L.push('Values held without a current verification (no source, or carried over from an earlier cycle).');
  L.push('Shown to students only as "Previously recorded, not verified". Confirm or correct each one.');
  L.push('');
  L.push('| Course | Category | Recorded value |');
  L.push('|---|---|---|');
  for (const r of recorded) L.push(`| \`${r.c.id}\` | ${r.cat.label} | ${md(r.value)} |`);
  L.push('');

  L.push('## Not verified, by course');
  L.push('');
  L.push('Hints point at wording in the course\'s existing source notes that may answer an unverified');
  L.push('category — check the official source; never copy a hint in as a value.');
  L.push('');
  L.push('| Course | University | Not verified | Reviewer hints |');
  L.push('|---|---|---|---|');
  for (const u of unverified) {
    L.push(`| \`${u.c.id}\` | ${md(u.c.university)} | ${u.missing.join(', ')} | ${u.hints.join('; ')} |`);
  }
  L.push('');
  return L.join('\n');
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname);
if (isMain) {
  fs.mkdirSync(path.dirname(REPORT_PATH), { recursive: true });
  fs.writeFileSync(REPORT_PATH, buildReport());
  console.log(`Wrote ${path.relative(ROOT, REPORT_PATH)}.`);
}
